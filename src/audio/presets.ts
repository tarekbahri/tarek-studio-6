export function loadUserPresets(): SynthPatch[] {
  try {
    const raw = localStorage.getItem(USER_PRESETS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.map((p) => createBasePatch({ ...p, isFactory: false }));
  } catch {
    return [];
  }
}

export function saveUserPresets(presets: SynthPatch[]): void {
  const clean = presets.map((p) => ({ ...p, isFactory: false }));
  const serialized = JSON.stringify(clean);
  try {
    localStorage.setItem(USER_PRESETS_KEY, serialized);
  } catch {
    // ignore storage quota errors
  }
  void mirrorKeyToIndexedDb(USER_PRESETS_KEY, serialized);
}

export function loadActivePatch(): SynthPatch {
  try {
    const raw = localStorage.getItem(ACTIVE_PATCH_KEY);
    if (!raw) return clonePatch(FACTORY_PRESETS[0]);
    const parsed = JSON.parse(raw);
    return createBasePatch(parsed);
  } catch {
    return clonePatch(FACTORY_PRESETS[0]);
  }
}

export function saveActivePatch(patch: SynthPatch): void {
  const serialized = JSON.stringify(patch);
  try {
    localStorage.setItem(ACTIVE_PATCH_KEY, serialized);
  } catch {
    // ignore storage quota errors
  }
  void mirrorKeyToIndexedDb(ACTIVE_PATCH_KEY, serialized);
}

export function clonePatch(patch: SynthPatch): SynthPatch {
  return JSON.parse(JSON.stringify(patch)) as SynthPatch;
}
