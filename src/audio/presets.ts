export function makeDefaultMacros(
  values: [number, number, number, number] = [0.5, 0.5, 0.5, 0.5],
  overrides?: Partial<Record<1 | 2 | 3 | 4, { name?: string; bindings?: MacroBinding[] }>>
): [SynthMacro, SynthMacro, SynthMacro, SynthMacro] {
  const defaults: [SynthMacro, SynthMacro, SynthMacro, SynthMacro] = [
    {
      id: 1,
      name: overrides?.[1]?.name ?? 'WOBBLE SPEED',
      value: values[0],
      bindings: overrides?.[1]?.bindings ?? [{ target: 'WOBBLE_SPEED', amount: 1.0 }],
    },
    {
      id: 2,
      name: overrides?.[2]?.name ?? 'GROWL INTENSITY',
      value: values[1],
      bindings: overrides?.[2]?.bindings ?? [
        { target: 'OSC_A_WT', amount: 0.5 },
        { target: 'OSC_A_WARP', amount: 0.48 },
        { target: 'OSC_B_WT', amount: 0.35 },
        { target: 'FILTER_DRIVE', amount: 0.45 },
      ],
    },
    {
      id: 3,
      name: overrides?.[3]?.name ?? 'FILTER MOVEMENT',
      value: values[2],
      bindings: overrides?.[3]?.bindings ?? [
        { target: 'FILTER_MOVEMENT', amount: 0.85 },
        { target: 'FILTER_CUTOFF', amount: 0.35 },
        { target: 'FILTER_RES', amount: 0.3 },
      ],
    },
    {
      id: 4,
      name: overrides?.[4]?.name ?? 'DISTORTION AMOUNT',
      value: values[3],
      bindings: overrides?.[4]?.bindings ?? [
        { target: 'FX_DIST_DRIVE', amount: 0.78 },
        { target: 'FX_DIST_MIX', amount: 0.45 },
      ],
    },
  ];
  return defaults;
}

function makeDefaultLfo(id: 1 | 2 | 3, overrides?: Partial<LfoConfig>): LfoConfig {
  const shape = overrides?.presetShape ?? (id === 1 ? 'wobble' : id === 2 ? 'triangle' : 'sine');
  return {
    id,
    presetShape: shape,
    points: overrides?.points ?? generateLfoPoints(shape),
    rateHz: id === 1 ? 2.4 : id === 2 ? 0.5 : 4.0,
    sync: id === 1,
    division: id === 1 ? '1/8' : id === 2 ? '1/4' : '1/16',
    depth: 0.75,
    bipolar: false,
    retrigger: true,
    ...overrides,
  };
}

function makeOsc(id: 'A' | 'B' | 'C', overrides?: Partial<OscillatorConfig>): OscillatorConfig {
  return {
    id,
    enabled: id === 'A',
    wavetableId: 'basic_shapes',
    wtPosition: id === 'B' ? 10 / 15 : 0.0,
    warpMode: 'none',
    warpAmount: 0,
    octave: id === 'C' ? -1 : 0,
    semitone: 0,
    detune: 0,
    unisonVoices: 1,
    unisonDetune: 0.2,
    level: id === 'A' ? 0.85 : id === 'B' ? 0.7 : 0.5,
    pan: 0,
    ...overrides,
  };
}

